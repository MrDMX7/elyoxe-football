"""Build stadiums.yaml from the sources (run by hand when the league adds a venue; the poller only reads it).

  * coordinates, capacity, FotMob name: matchDetails infoBox.Stadium of every published UAE Pro League
    and League Cup match, plus each club's home venue from its FotMob team page;
  * official English and Arabic names: uaepl.ae fixtures (same match joined on UAE date + home club).
Sequential, 0.5 s between requests.   python tools/seed_stadiums.py > stadiums.yaml.new
"""
import re, sys, time
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import config  # noqa: E402
from sources.fotmob import FotMob  # noqa: E402
from sources.uaepl import UaePL  # noqa: E402
from timeutil import parse_utc, UAE  # noqa: E402

CITY_EMIRATE = [("ain", "abu-dhabi", "Al Ain"), ("abu", "abu-dhabi", "Abu Dhabi"), ("dhabi", "abu-dhabi", "Abu Dhabi"),
                ("dubai", "dubai", "Dubai"), ("dubayy", "dubai", "Dubai"), ("hatta", "dubai", "Hatta"),
                ("sharjah", "sharjah", "Sharjah"), ("shariqah", "sharjah", "Sharjah"), ("khor", "sharjah", "Khor Fakkan"),
                ("kalba", "sharjah", "Kalba"), ("ajman", "ajman", "Ajman"), ("fujairah", "fujairah", "Fujairah"),
                ("ras al", "ras-al-khaimah", "Ras Al Khaimah"), ("umm al", "umm-al-quwain", "Umm Al Quwain"),
                ("zayed city", "abu-dhabi", "Madinat Zayed"), ("madinat", "abu-dhabi", "Madinat Zayed")]


def emirate_of(city, name):
    t = f"{city or ''} {name or ''}".lower()
    for w, em, c in CITY_EMIRATE:
        if w in t:
            return em, c
    return None, city


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", (s or "").lower()).strip("-")


def main():
    fm, up = FotMob(), UaePL()
    venues = {}                       # fotmob name -> {lat, lon, capacity, city, matches: set, homes: set}
    pair = defaultdict(lambda: defaultdict(int))   # fotmob name -> {(en, ar): count}
    for cid in (538, 11027):
        comp = config.competition(cid)
        c = fm.competition({"id": cid}, with_leaders=False)
        ul = {}
        try:
            for f in up.fixtures(comp):
                if f["kickoff_utc"] and f["home"]["id"]:
                    ul[(f["kickoff_utc"][:10], f["home"]["id"])] = f
        except Exception as e:
            print(f"# uaepl {cid}: {e}", file=sys.stderr)
        for m in c["matches"]:
            try:
                d = fm.match(m["id"])
            except Exception as e:
                print(f"# match {m['id']}: {e}", file=sys.stderr)
                continue
            v = d.get("venue")
            time.sleep(0.5)
            if not v or v.get("lat") is None:
                continue
            e = venues.setdefault(v["name"], {"lat": v["lat"], "lon": v["lon"], "capacity": v.get("capacity"),
                                              "city": v.get("city"), "matches": set(), "homes": set()})
            e["matches"].add(m["id"])
            e["homes"].add(m["home"]["id"])
            u = ul.get(((m["kickoff_utc"] or "")[:10], m["home"]["id"]))
            if u and u.get("venue_name"):
                pair[v["name"]][(u["venue_name"], u["venue_name_ar"])] += 1
    homes = {}
    for tid in sorted({t for v in venues.values() for t in v["homes"]}):
        try:
            t = fm.team(tid)
            if t.get("venue") and t["venue"].get("lat") is not None:
                homes[tid] = t["venue"]
                venues.setdefault(t["venue"]["name"], {"lat": t["venue"]["lat"], "lon": t["venue"]["lon"], "capacity": None,
                                                       "city": t["venue"]["city"], "matches": set(), "homes": set()})
        except Exception as e:
            print(f"# team {tid}: {e}", file=sys.stderr)
        time.sleep(0.5)
    print("# Stadiums used by UAE club competitions. Generated by tools/seed_stadiums.py, then reviewed by hand.")
    print("#   lat/lon: FotMob matchDetails infoBox.Stadium (sources lists the match ids) or team page venue")
    print("#   name_en/name_ar: uaepl.ae fixtures for the same match (official names)")
    print("#   home_of: FotMob team ids whose team page names this stadium as home")
    print("stadiums:")
    for name, v in sorted(venues.items()):
        best = max(pair[name].items(), key=lambda kv: kv[1])[0] if pair[name] else (None, None)
        em, city = emirate_of(v["city"], name)
        home_of = sorted(t for t, hv in homes.items() if hv["name"] == name)
        print(f"  - id: {slug(best[0] or name)}")
        print(f"    name_en: {best[0] or name}")
        print(f"    name_ar: {best[1] or ''}")
        print(f"    fotmob_name: {name}")
        print(f"    city: {city}")
        print(f"    emirate: {em}")
        print(f"    lat: {round(float(v['lat']), 6)}")
        print(f"    lon: {round(float(v['lon']), 6)}")
        if v.get("capacity"):
            print(f"    capacity: {v['capacity']}")
        if home_of:
            print(f"    home_of: {home_of}")
        src = sorted(v["matches"])[:3]
        print(f"    sources: [fotmob matchDetails {', '.join(map(str, src)) or 'n/a'}{'; fotmob team venue' if home_of else ''}"
              f"{'; uaepl.ae fixtures' if best[0] else ''}]")


if __name__ == "__main__":
    main()
